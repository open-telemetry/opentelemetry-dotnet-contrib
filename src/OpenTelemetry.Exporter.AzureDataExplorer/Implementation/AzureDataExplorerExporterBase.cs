using System.Diagnostics;
using OpenTelemetry.Internal;
using OpenTelemetry.Resources;

namespace OpenTelemetry.Exporter.AzureDataExplorer;

/// <summary>
/// Shared implementation for the Azure Data Explorer exporters: buffers rows as
/// newline-delimited JSON and ingests them with timeout and retry handling.
/// </summary>
/// <typeparam name="T">Telemetry type.</typeparam>
internal abstract class AzureDataExplorerExporterBase<T> : BaseExporter<T>
    where T : class
{
    private readonly IAzureDataExplorerIngestor ingestor;
    private readonly JsonRowWriter rows = new();
    private readonly ManualResetEventSlim shutdownEvent = new(false);
    private readonly CancellationTokenSource shutdownCts = new();
    private readonly TimeSpan exportTimeout;
    private readonly bool retryOnFailure;
    private readonly TimeSpan retryInitialInterval;
    private readonly TimeSpan retryMaxInterval;
    private AttributeMap? resourceAttributes;
    private int ingestorDisposed;
    private bool disposed;

    protected AzureDataExplorerExporterBase(AzureDataExplorerExporterOptions options, string signal, string tableName, string? jsonMapping)
    {
        Guard.ThrowIfNull(options);

        options.Validate();

        if (string.IsNullOrWhiteSpace(tableName))
        {
            throw new InvalidOperationException($"The {signal} table name is mandatory.");
        }

        this.Signal = signal;
        this.TableName = tableName;
        this.exportTimeout = options.ExportTimeout;
        this.retryOnFailure = options.RetryOnFailure;
        this.retryInitialInterval = options.RetryInitialInterval;
        this.retryMaxInterval = options.RetryMaxInterval;

#pragma warning disable CA2000 // Dispose objects before losing scope - owned and disposed by this exporter.
        this.ingestor = options.IngestorFactory != null
            ? options.IngestorFactory(tableName, jsonMapping)
            : KustoRestIngestor.Create(options, tableName, jsonMapping);
#pragma warning restore CA2000
    }

    internal string Signal { get; }

    internal string TableName { get; }

    internal IAzureDataExplorerIngestor Ingestor => this.ingestor;

    /// <inheritdoc/>
    public override ExportResult Export(in Batch<T> batch)
    {
        // Prevent recursive telemetry generated by the Azure SDK from being captured.
        using var scope = SuppressInstrumentationScope.Begin();

        try
        {
            this.rows.Clear();
            var resource = this.GetResourceAttributes();

            foreach (var item in batch)
            {
                this.Serialize(this.rows, item, resource);
            }

            if (this.rows.RowCount == 0)
            {
                return ExportResult.Success;
            }

            return this.Ingest();
        }
        catch (Exception ex)
        {
            AzureDataExplorerExporterEventSource.Log.ExportFailed(this.Signal, this.TableName, ex);
            return ExportResult.Failure;
        }
    }

    internal static bool IsPermanent(Exception exception)
        => AzureDataExplorerIngestionException.IsPermanentError(exception);

    internal TimeSpan GetRetryDelay(int attempt)
    {
        var multiplier = Math.Pow(2, Math.Min(attempt - 1, 30));
        var delayMs = Math.Min(this.retryInitialInterval.TotalMilliseconds * multiplier, this.retryMaxInterval.TotalMilliseconds);
        return TimeSpan.FromMilliseconds(Math.Max(0, delayMs));
    }

    protected abstract void Serialize(JsonRowWriter rows, T item, AttributeMap resourceAttributes);

    protected virtual void OnResourceResolved(Resource resource)
    {
    }

    /// <inheritdoc/>
    protected override bool OnShutdown(int timeoutMilliseconds)
    {
        this.SignalShutdown();
        this.DisposeIngestor();
        return true;
    }

    /// <inheritdoc/>
    protected override void Dispose(bool disposing)
    {
        if (!this.disposed)
        {
            if (disposing)
            {
                this.SignalShutdown();
                this.DisposeIngestor();
                this.rows.Dispose();
                this.shutdownEvent.Dispose();
                this.shutdownCts.Dispose();
            }

            this.disposed = true;
        }

        base.Dispose(disposing);
    }

    private ExportResult Ingest()
    {
        var stopwatch = Stopwatch.StartNew();
        var hasDeadline = this.exportTimeout != Timeout.InfiniteTimeSpan;
        var attempt = 0;

        while (true)
        {
            attempt++;

            var remaining = hasDeadline ? this.exportTimeout - stopwatch.Elapsed : Timeout.InfiniteTimeSpan;
            if (hasDeadline && remaining <= TimeSpan.Zero)
            {
                AzureDataExplorerExporterEventSource.Log.ExportFailed(this.Signal, this.TableName, new TimeoutException("The export timed out."));
                return ExportResult.Failure;
            }

            try
            {
                using var cts = CancellationTokenSource.CreateLinkedTokenSource(this.shutdownCts.Token);
                cts.CancelAfter(remaining);
                this.rows.Buffer.Position = 0;
                this.ingestor.IngestAsync(this.rows.Buffer, cts.Token).GetAwaiter().GetResult();
                return ExportResult.Success;
            }
            catch (Exception ex)
            {
                if (!this.retryOnFailure || IsPermanent(ex) || this.shutdownEvent.IsSet)
                {
                    AzureDataExplorerExporterEventSource.Log.ExportFailed(this.Signal, this.TableName, ex);
                    return ExportResult.Failure;
                }

                var delay = this.GetRetryDelay(attempt);
                if (hasDeadline && stopwatch.Elapsed + delay >= this.exportTimeout)
                {
                    AzureDataExplorerExporterEventSource.Log.ExportFailed(this.Signal, this.TableName, ex);
                    return ExportResult.Failure;
                }

                AzureDataExplorerExporterEventSource.Log.ExportRetrying(this.Signal, this.TableName, attempt, delay, ex);

                if (this.shutdownEvent.Wait(delay))
                {
                    // Shutdown was requested while waiting to retry.
                    return ExportResult.Failure;
                }
            }
        }
    }

    private AttributeMap GetResourceAttributes()
    {
        if (this.resourceAttributes != null)
        {
            return this.resourceAttributes;
        }

        var resource = this.ParentProvider?.GetResource() ?? Resource.Empty;
        var map = new AttributeMap();
        foreach (var attribute in resource.Attributes)
        {
            map.Set(attribute.Key, attribute.Value);
        }

        this.OnResourceResolved(resource);

        // Only cache once the exporter is attached to a provider so the
        // provider's resource is picked up.
        if (this.ParentProvider != null)
        {
            this.resourceAttributes = map;
        }

        return map;
    }

    private void SignalShutdown()
    {
        this.shutdownEvent.Set();

        // Abort any in-flight ingestion so shutdown is not blocked by network calls.
        try
        {
            this.shutdownCts.Cancel();
        }
        catch (ObjectDisposedException)
        {
        }
        catch (AggregateException ex)
        {
            AzureDataExplorerExporterEventSource.Log.IngestorDisposeFailed(this.Signal, ex);
        }
    }

    private void DisposeIngestor()
    {
        if (Interlocked.Exchange(ref this.ingestorDisposed, 1) != 0)
        {
            return;
        }

        try
        {
            this.ingestor.Dispose();
        }
        catch (Exception ex)
        {
            AzureDataExplorerExporterEventSource.Log.IngestorDisposeFailed(this.Signal, ex);
        }
    }
}
